/* V5 end-to-end UI: synthetic hotel, no external network or actual money. */
import assert from 'node:assert/strict';
import {openDatabase} from '../src/database.js';
import {createApp} from '../src/server.js';
import {createPasswordRecord} from '../src/auth.js';
import {createStaff} from '../src/staff.js';
import {importMenuCsv} from '../src/restaurant.js';
import {renderRestaurantReceipt} from '../src/restaurant-receipt.js';

export async function runV5WorkflowSmoke(browser){
  const db=openDatabase(':memory:');
  const ownerPassword='v5-synthetic-owner-password-strong';
  const staffPassword='v5-synthetic-cashier-password-strong';
  importMenuCsv(db,'name,category,price,tax_rate\nMasala Chai,Drinks,80,5');
  createStaff(db,{username:'cashierqa',display_name:'Synthetic Cashier',role:'cashier',password:staffPassword});
  const server=createApp(db,{authRecord:createPasswordRecord(ownerPassword)}).listen(0,'127.0.0.1');
  await new Promise(r=>server.once('listening',r));
  const base='http://127.0.0.1:'+server.address().port;
  const context=await browser.newContext({viewport:{width:1280,height:850}});
  try{
    const page=await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/login.html');
    assert.equal(await page.locator('#login-pin-toggle').isVisible(),false);
    await page.locator('input[name=username]').fill('owner');
    await page.locator('input[name=password]').fill(ownerPassword);
    await page.getByRole('button',{name:'Sign in'}).click();
    await page.waitForURL(base+'/');
    await page.goto(base+'/#restaurant');
    await page.locator('#restaurant').waitFor({state:'visible'});
    await page.locator('#restaurant-table-management > summary').click();
    await page.locator('#restaurant-table-new').fill('Courtyard 1');
    await page.locator('#restaurant-table-create button').click();
    await page.waitForFunction(()=>document.querySelector('#restaurant-table-admin-message')?.textContent?.includes('added'));
    assert.equal(db.prepare('SELECT COUNT(*) n FROM restaurant_tables').get().n,1);
    await page.locator('#logout').click();
    await page.waitForURL(base+'/login.html');
    await page.locator('input[name=username]').fill('cashierqa');
    await page.locator('input[name=password]').fill(staffPassword);
    await page.getByRole('button',{name:'Sign in'}).click();
    await page.waitForURL(base+'/');
    await page.goto(base+'/#restaurant');
    await page.locator('#restaurant').waitFor({state:'visible'});
    await page.locator('#restaurant-table').selectOption({label:'Courtyard 1'});
    await page.getByRole('button',{name:'Add Masala Chai to bill'}).click();
    await page.locator('#review-restaurant-bill').click();
    assert.match(await page.locator('#restaurant-review-payment').textContent(),/Table Courtyard 1/);
    page.once('dialog',d=>d.accept());
    await page.locator('#save-restaurant-bill').click();
    await page.waitForFunction(()=>document.querySelector('#restaurant-message')?.textContent?.includes('saved once'));
    const billId=db.prepare('SELECT id FROM restaurant_bills ORDER BY id DESC LIMIT 1').get().id;
    assert.match(renderRestaurantReceipt(db,billId),/Table: Courtyard 1/);
    assert.equal(db.prepare('SELECT table_label FROM restaurant_bill_tables').get().table_label,'Courtyard 1');
    assert.match(await page.locator('#restaurant-history').textContent(),/Courtyard 1/);
    await page.locator('#logout').click();
    await page.waitForURL(base+'/login.html');
    await page.locator('input[name=username]').fill('owner');
    await page.locator('input[name=password]').fill(ownerPassword);
    await page.getByRole('button',{name:'Sign in'}).click();
    await page.waitForURL(base+'/');
    await page.goto(base+'/#restaurant');
    await page.locator('#restaurant').waitFor({state:'visible'});
    await page.locator('#menu-import-section > summary').click();
    await page.locator('#menu-availability-section > summary').click();
    await page.waitForFunction(()=>document.querySelector('#menu-availability-count')?.textContent?.includes('1 of 1'));
    await page.getByRole('button',{name:'Edit current price and GST for Masala Chai'}).click();
    await page.locator('#menu-price-form [name=price]').fill('120');
    await page.locator('#menu-price-form [name=tax_rate]').fill('5');
    await page.locator('#menu-price-form [name=reason]').fill('Reviewed revised synthetic menu price');
    page.once('dialog',d=>d.accept());
    await page.locator('#menu-price-form button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelector('#menu-availability-message')?.textContent?.includes('updated for new bills'));
    assert.equal(db.prepare('SELECT price_paise FROM menu_items').get().price_paise,12000);
    assert.equal(db.prepare('SELECT total_paise FROM restaurant_bills WHERE id=?').get(billId).total_paise,8000);
    await page.goto(base+'/#profile');
    await page.locator('#owner-staff-pin').waitFor({state:'visible'});
    await page.locator('#owner-staff-pin-form [name=current_password]').fill(ownerPassword);
    page.once('dialog',d=>d.accept());
    await page.locator('#owner-staff-pin-toggle').click();
    await page.waitForFunction(()=>document.querySelector('#owner-staff-pin-state')?.textContent?.includes('enabled'));
    await page.locator('#logout').click();
    await page.waitForURL(base+'/login.html');
    await page.locator('input[name=username]').fill('cashierqa');
    await page.locator('input[name=password]').fill(staffPassword);
    await page.getByRole('button',{name:'Sign in'}).click();
    await page.waitForURL(base+'/');
    await page.goto(base+'/#profile');
    await page.locator('#profile-quick-pin').waitFor({state:'visible'});
    await page.locator('#profile-quick-pin-form [name=current_password]').fill(staffPassword);
    await page.locator('#profile-quick-pin-form [name=pin]').fill('012345');
    await page.locator('#profile-quick-pin-form [name=confirm_pin]').fill('012345');
    await page.locator('#profile-quick-pin-form button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelector('#profile-quick-pin-message')?.textContent?.includes('registered'));
    await page.locator('#logout').click();
    await page.waitForURL(base+'/login.html');
    await page.locator('#login-pin-toggle').waitFor({state:'visible'});
    await page.locator('#login-pin-toggle').click();
    assert.equal(await page.locator('#login-pin-field').isVisible(),true);
    assert.equal(await page.locator('#login-password-field').isVisible(),false);
    await page.locator('input[name=username]').fill('cashierqa');
    await page.locator('input[name=pin]').fill('012345');
    await page.getByRole('button',{name:'Sign in'}).click();
    await page.waitForURL(base+'/');
    await page.waitForFunction(()=>document.querySelector('#profile-name')?.textContent?.includes('Synthetic Cashier'));
    assert.equal((await (await context.request.get(base+'/api/me')).json()).login_method,'pin');
    assert.equal(await page.locator('#staff-admin').isVisible(),false);
    assert.equal(await page.locator('#restaurant-table-management').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log('PASS: V5 sidebar/table receipts, manager price review, owner PIN opt-in and cashier device login');
  }finally{
    await context.close();
    await new Promise(r=>server.close(r));
    db.close();
  }
}
